/**
 * 作者识别的**定量**回归测试。
 *
 * 为什么需要这个文件：`test/author-kind.test.ts` 里全是**举例式**断言
 * （`筚路维艰 - 萧冬连` 判得对），它只能防止「某个已知用例回退」，
 * 不能反映整体水平。分类准确率是「按作者」浏览能不能用的前提，
 * 所以必须有一个人类可读的分数在 CI 里可见。
 *
 * 判据演进史（都是实测出来的，不是推测）：
 *
 *   基线                75.2%   早期实现用「长度」猜人名（2–3 字 +4、4 字 +1）
 *   + 兜底改为书名在前  87.2%   长度启发在中文上根本不成立
 *   + 姓氏长度约束      90.6%   中文书名首字是常见姓氏的概率极高
 *   + 书名结构特征      91.5%   「记/传/演义/志」结尾几乎不会是人名
 *
 * 中间一次「优化」把分数打到 40% —— 因为只扩了姓氏表却没改兜底方向，
 * 于是「两边都判不出」时仍按「作者在左」处理，把所有**无姓笔名**
 * （紫金陈、老舍、加缪、兰陵笑笑生、今何在）全部判反。
 * 教训：单个判据的改进不代表整体改进，必须有定量基准。
 *
 * 剩余约 8.5% 属中文歧义的硬边界（`白夜 - 老舍` 这类两字词），
 * 再加规则就会开始过拟合测试集。这里**刻意不追求 100%**。
 */

