/**
 * 多音字上下文表 —— **人工维护**，与 `pinyin-table.ts`（自动生成）互补。
 *
 * ── 问题 ────────────────────────────────────────────────────────────────
 * `pinyin-table.ts` 是一张「单字 → 默认读音首字母」的静态表（脚本生成），
 * 它只认单个字的**默认读音**。于是凡是多音字开头的中文书名/作者，归桶都可能错：
 *
 *   重庆 → C（chóng 才是对的，应 Q）    厦门 → S（xià，应 X）
 *   单田芳 → D（shàn，应 S）            查良镛 → C（zhā，应 Z）
 *   犍为 → J（qián，应 Q）              乐清 → L（yuè，应 Y）
 *
 * 而 `letterBucket()` 手里其实有**完整字符串**（书名或作者名），
 * 完全可以用「首字后面跟的是什么」来判读音。这张表就是那个「上下文」。
 *
 * ── 为什么不用 pinyin-pro 自动生成 ──────────────────────────────────────
 * 已实测（pinyin-pro 3.29.5）：`pinyin('重庆', { pattern: 'first' })` 返回
 * `['c', 'q']` —— 它**对词也不做多音字消歧**，仍然按单字默认读音给。
 * 同类实测：`pinyin('尉迟')` → `wei chi`（应 yù chí）、`pinyin('万俟卨')`
 * → `wan si xie`（应 mò qí xiè）、`pinyin('澹台')` → `dan tai`（应 tán tái）。
 * 也就是说：自动生成这条路在这里是**假路**，词条只能人工维护。
 * （生成脚本仍留在 `scripts/gen-pinyin-table.mjs`，它只负责单字默认读音。）
 *
 * ── 为什么不用现成词库 ──────────────────────────────────────────────────
 * 运行时要零依赖（Worker 体积限制），一张开放的现代汉语词库动辄几 MB，
 * 与「首字母分桶」这个收益完全不成比例。所以这里只收录**高频且高价值**的
 * 冲突：地名、姓氏、常见的「同形不同音」词。
 *
 * ── 读音依据（每条都在下面逐条注明）───────────────────────────────────
 *   · 《现代汉语词典》第 7 版（简称「现汉」）
 *   · 教育部《重編國語辭典修訂本》（简称「国语辞典」，台湾官方，读音与普通话一致）
 *   · 维基百科/百度百科的地名条目（地名读音以当地官方和词典为准）
 *   · 民政部/山东省民政厅《100 个中国最难读的地名》这类官方整理
 *
 * ── 匹配规则 ────────────────────────────────────────────────────────────
 *   1. 只在**首字**是汉字时查表（拉丁字母/数字开头的字符串原样交给调用方）。
 *   2. 词条按「最长前缀优先」匹配：`重庆市` 先试 3 字，再试 `重庆` → Q。
 *   3. 词条没命中时看**姓氏规则**，但它只在「整串恰好 3 个汉字」时生效。
 *      为什么卡 3 字：中文人名「姓 + 1~2 字名」以 3 字最常见，而 2 字串
 *      与常用词（单纯/仇恨/区别/乐观）**在纯字符串层面完全无法区分**，
 *      4 字以上的串更可能是标题（查无此人、单向度的人、解忧杂货店），
 *      那些都是词的本音。这个取舍是「宁少错、不多错」。
 *   4. 都没命中 → 返回 null，调用方回落到 `pinyinInitial()` 的单字默认读音。
 *
 * ── 边界（不要指望它能"修好多音字"）─────────────────────────────────────
 *   下面几条都是**实测**结果（2026-10-20，`letterBucket()` 实际输出），
 *   不是推测 —— 写在这里是为了让下一个人知道「哪里还会错」，而不是以为全好了：
 *
 *   · **表外多音字仍会错**：「重耳」（晋文公，chóng）未收录 → 实测落 **Z**
 *     （正确应是 C）。这是刻意的边界：收录一条错读音比不收录更糟，
 *     所以每条都单独核对过才进表，宁可留错也不猜。
 *   · **表内词条只按前缀匹配**：「区家」实测落 **Q**（qu），而「区家麟」落 O
 *     —— 因为姓氏规则要求整串恰好 3 个汉字，而「区家」这个 2 字串会先命中
 *     别的东西（详细约束见下面的匹配规则）。单字姓氏本来就无法与常用词区分。
 *   · **同首字不同音仍要靠逐词收录**：「藏地密码」实测落 **C**（cáng，正确），
 *     而「藏族」落 **Z** —— 同一个「藏」在两条词里不同音，表里只有逐词条目
 *     才能分开，不能用「藏 + 任意」粗暴匹配（那会把「藏地密码」也判成 Z）。
 *   · 姓氏规则只覆盖 3 字串，2 字人名靠专名条目（曾朴/仇英/解缙/乐毅）。
 *   · 一声/轻声、声调不参与判定 —— 分桶只需要首字母，声调对桶无影响。
 */

/** CJK 主区 + 扩展 A + 兼容区（与 letterBucket 用的字符类保持一致） */
const HANZI = /[\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff]/;

/** 「可定序」字符：拉丁字母 / 数字 / 汉字。首个这类字符决定归桶。 */
const ORDERABLE = /[A-Za-z0-9\u3400-\u4dbf\u4e00-\u9fff\uf900-\ufaff]/;

