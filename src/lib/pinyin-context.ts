/**
 * 姓氏规则：[姓氏, 该姓读音的首字母]。
 *
 * ⚠️ 只在「整串恰好 3 个汉字」时生效（见文件头的取舍说明）：
 *    3 字是中文人名最常见的形状（单田芳、查良镛、区家麟、曾国藩）。
 *    2 字串与常用词无法区分（单纯 vs 单雄），所以 2 字人名改由上面的专名条目收。
 *
 * 只收「姓氏读音与单字默认读音**不同**」的姓。以下几个常被提到的姓氏
 * **故意不在这里**，因为它们的姓氏读音首字母与默认读音相同，加了也不改变结果：
 *   覃 qín = Q（默认即 Q）   柏 bǎi = B（默认即 B）   朴 piáo = P（默认即 P）
 */
const SURNAME_RULES: ReadonlyArray<readonly [string, string]> = [
  ['单', 'S'],
  ['曾', 'Z'],
  ['解', 'X'],
  ['查', 'Z'],
  ['仇', 'Q'],
  ['区', 'O'],
  ['乐', 'Y'],
];

/** 词 → 首字母（模块加载时构建一次；O(1) 前缀查找，不逐条 startsWith 扫描） */
const WORD_INITIALS = new Map<string, string>();
let MAX_WORD_LEN = 2;
for (const [, letter, words] of WORD_RULES) {
  for (const w of words.split(' ')) {
    WORD_INITIALS.set(w, letter);
    if (w.length > MAX_WORD_LEN) MAX_WORD_LEN = w.length;
  }
}

/** 姓氏 → 首字母 */
const SURNAME_INITIALS = new Map<string, string>(SURNAME_RULES);

/**
 * 按上下文取**首字**的拼音首字母；命中不了返回 null（调用方回落单字读音）。
 *
 * 只处理「首个可定序字符是汉字」的字符串；拉丁字母/数字开头一律返回 null，
 * 让 `letterBucket()` 自己处理（那是它原有的逻辑，本模块不碰）。
 * 前导的标点/空白/书名号照旧跳过 —— `《重庆谈判》` 与 `重庆谈判` 同样命中。
 */
export function contextualInitial(input: string | null | undefined): string | null {
  const text = (input ?? '').trim();
  if (text.length === 0) return null;

  // 找第一个「可定序」字符：必须是汉字，否则不归本表管
  const m = ORDERABLE.exec(text);
  if (!m || !HANZI.test(m[0])) return null;

  const head = text.slice(m.index);
  // 汉字前缀长度：遇到标点/拉丁/数字就停（「阿Q正传」的汉字前缀只有「阿」）
  let hzLen = 0;
  while (hzLen < head.length && HANZI.test(head[hzLen]!)) hzLen++;
  const hz = head.slice(0, hzLen);

  // ① 最长前缀优先：`重庆市` 先试 3 字，再试 `重庆`
  for (let len = Math.min(MAX_WORD_LEN, hz.length); len >= 2; len--) {
    const hit = WORD_INITIALS.get(hz.slice(0, len));
    if (hit) return hit;
  }

  // ② 姓氏规则：只对 3 字串生效（理由见文件头）
  if (hzLen === 3) {
    const hit = SURNAME_INITIALS.get(hz[0]!);
    if (hit) return hit;
  }

  return null;
}
