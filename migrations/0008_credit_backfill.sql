-- webooks migration 0008：把「没留名」的书统一归到雷锋
--
-- 为什么需要这条独立迁移（0007 里已经有一句相同的回填）：
--
-- 0007 加列时的回填是 `WHERE credit IS NULL`。但实际上「没留名」有
-- **三种**形态，散落在不同路径写入：
--
--   1. NULL            —— 0007 之前就存在的存量书（若回填没跑到）
--   2. 空字符串 ''     —— 某些写入路径把空串直接存了进去
--   3. '雷锋'          —— 0007 之后走正常上传流程的书
--
-- 只处理 (1) 会漏掉 (2)。而榜单的查询条件是
-- `credit IS NOT NULL AND credit <> ''` —— (2) 既不在榜也不算总数，
-- 表现为「书库里明明有这本书，账算不平」。
--
-- 这条迁移是**幂等**的：可以反复执行，不会改变已经正确的值。
--
-- ⚠️ 它同时修正了「雷锋计入榜单」这个决定带来的必然要求 ——
--    集体署名要能代表**所有**没留名的人，就不能有任何一本书漏在它外面。

UPDATE books SET credit = '雷锋'
 WHERE credit IS NULL OR TRIM(credit) = '';

-- ⚠️ 只把纯空白的改掉，不要碰用户真的写了空格的名字 ——
--    上面已经用 TRIM('') 限定了，但显式说明意图：
--    一个叫「  」的署名会被当作没留名，这是刻意的（它没有信息量）。
